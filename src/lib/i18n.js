export function makeTranslator(language) {
  return (key, vars = {}) => {
    const value = copy[language]?.[key] ?? copy.en[key] ?? key;
    if (Array.isArray(value)) return value;
    return value.replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? `{${name}}`));
  };
}
